    if (poet.poem1 != null && poet.poem1!.isNotEmpty) {
      allPoems.add(poet.poem1!);
      poemTitles.add('شعر اول');
    }
    if (poet.poem2 != null && poet.poem2!.isNotEmpty) {
      allPoems.add(poet.poem2!);
      poemTitles.add('شعر دوم');
    }
    if (poet.poem3 != null && poet.poem3!.isNotEmpty) {
      allPoems.add(poet.poem3!);
      poemTitles.add('شعر سوم');
    }
    if (poet.poem4 != null && poet.poem4!.isNotEmpty) {
      allPoems.add(poet.poem4!);
      poemTitles.add('شعر چهارم');
    }
    if (poet.poem5 != null && poet.poem5!.isNotEmpty) {
      allPoems.add(poet.poem5!);
      poemTitles.add('شعر پنجم');
    }
    
    if (allPoems.isEmpty) return const SizedBox.shrink();
    
    return Column(
      children: [
        for (int i = 0; i < allPoems.length; i++)
          Column(
            children: [
              _buildSinglePoemCard(
                context, 
                allPoems[i], 
                poemTitles[i], 
                poet.name,
                isExpanded: poemExpandedState['poem$i'] ?? false,
                onToggle: () {
                  setState(() {
                    poemExpandedState['poem$i'] = !(poemExpandedState['poem$i'] ?? false);
                  });
                },
              ),
              if (i < allPoems.length - 1) const SizedBox(height: 16),
            ],
          ),
      ],
    );
  }

