  @override
  Widget build(BuildContext context) {
    // جستجو روی title و sections
    final filtered = traditionalItems.where((item) {
      if (searchText.isEmpty) return true;
      
      final title = item["title"] as String;
      final sections = item["sections"] as List<dynamic>;

      final matchInTitle = title.toLowerCase().contains(searchText.toLowerCase());
      final matchInSections = sections.any((section) {
        final content = (section["content"] as String).toLowerCase();
        final sectionTitle = (section["title"] as String).toLowerCase();
        return content.contains(searchText.toLowerCase()) || 
               sectionTitle.contains(searchText.toLowerCase());
      });

      return matchInTitle || matchInSections;
    }).toList();

    return Scaffold(
      appBar: AppBar(
        title: const Text(
          "مراسمات سنتی روستای ایراج",
          style: TextStyle(fontFamily: 'Vazirmatn', fontWeight: FontWeight.bold),
        ),
      ),
      body: Column(
        children: [
          // نوار جستجو
          Padding(
            padding: const EdgeInsets.all(12),
            child: TextField(
              onChanged: (value) => setState(() => searchText = value),
              decoration: InputDecoration(
                hintText: "جستجو در مراسمات...",
                prefixIcon: const Icon(Icons.search),
                border: OutlineInputBorder(
                  borderRadius: BorderRadius.circular(12),
