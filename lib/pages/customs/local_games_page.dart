
import 'package:flutter/material.dart';

class LocalGamesPage extends StatefulWidget {
  const LocalGamesPage({super.key});

  @override
  State<LocalGamesPage> createState() => _LocalGamesPageState();
}

class _LocalGamesPageState extends State<LocalGamesPage> {
  // متن جستجو
  String _searchText = "";

  // تابع نرمال‌سازی متن برای جستجو
  String _normalizeText(String text) {
    return text
        .replaceAll('ي', 'ی')
        .replaceAll('ك', 'ک')
        .replaceAll('\u200c', '')
        .replaceAll(RegExp(r'\s+'), ' ')
        .trim()
        .toLowerCase();
  }

  // فیلتر بازی‌ها بر اساس جستجو
  List<Map<String, dynamic>> _filterGames() {
    if (_searchText.isEmpty) return localGames;

    final normalizedQuery = _normalizeText(_searchText);

    return localGames.where((game) {
      return _normalizeText(game['name']).contains(normalizedQuery) ||
          _normalizeText(game['description']).contains(normalizedQuery) ||
          _normalizeText(game['players']).contains(normalizedQuery) ||
          _normalizeText(game['equipment']).contains(normalizedQuery) ||
          _normalizeText(game['details']).contains(normalizedQuery) ||
          _normalizeText(game['history']).contains(normalizedQuery);
    }).toList();
  }

  // تابع هایلایت کردن متن جستجو
  InlineSpan _highlightText(String text, String query) {
    if (query.isEmpty) return TextSpan(text: text);

    final normalizedText = _normalizeText(text);
    final normalizedQuery = _normalizeText(query);

    final spans = <TextSpan>[];
    int start = 0;

    while (true) {
      final index = normalizedText.indexOf(normalizedQuery, start);
      if (index == -1) {
        spans.add(TextSpan(text: text.substring(start)));
        break;
      }

      spans.add(TextSpan(text: text.substring(start, index)));

      spans.add(
        TextSpan(
          text: text.substring(index, index + query.length),
          style: const TextStyle(
            backgroundColor: Colors.yellow,
            color: Colors.black,
            fontWeight: FontWeight.bold,
          ),
        ),
      );

      start = index + query.length;
    }

    return TextSpan(
      children: spans,
      style: const TextStyle(color: Colors.black),
    );
  }

  // تابع فرمت‌بندی متن بازی
  InlineSpan _formatGameText(String text) {
    final List<InlineSpan> spans = [];
    final lines = text.split('\n');

    for (String line in lines) {
      line = line.trim();
      if (line.isEmpty) {
        spans.add(const TextSpan(text: '\n'));
        continue;
      }

      // بررسی آیا خط یک عنوان است
      bool isTitle = false;

      // حذف دو نقطه از انتهای خط اگر وجود دارد
      if (line.endsWith(':')) {
        line = line.substring(0, line.length - 1);
        isTitle = true;
      } else if (line.length < 120 &&
          !line.contains('.') &&
          !line.contains('،') &&
          !line.contains('؛') &&
          !line.contains(' و ') &&
          !line.startsWith('اگر') &&
          !line.startsWith('با ') &&
          !line.startsWith('در ')) {
        isTitle = true;
      }

      if (isTitle) {
        // خط عنوان - قرمز و بزرگ
        spans.add(
          TextSpan(
            text: '$line\n',
            style: TextStyle(
              color: Colors.red[700],
              fontSize: 19,
              fontWeight: FontWeight.bold,
              fontFamily: 'Vazir',
              height: 2.0,
            ),
          ),
        );
      } else if (line.startsWith('•') ||
          line.startsWith('- ') ||
          RegExp(r'^\d+\.').hasMatch(line)) {
        // خط‌های لیست
        spans.add(
          TextSpan(
            text: '$line\n',
            style: TextStyle(
              color: Colors.blueGrey[800],
              fontSize: 16,
              fontWeight: FontWeight.w600,

fontFamily: 'Vazir',
              height: 1.8,
            ),
          ),
        );
      } else if (line.contains('🎯') ||
          line.contains('📜') ||
          line.contains('🔄') ||
          line.contains('🏁') ||
          line.contains('⚖️') ||
          line.contains('🔼') ||
          line.contains('🔽')) {
        // خط‌های با ایموجی
        spans.add(
          TextSpan(
            text: '$line\n',
            style: TextStyle(
              color: Colors.green[800],
              fontSize: 18,
              fontWeight: FontWeight.bold,
              fontFamily: 'Vazir',
              height: 1.9,
            ),
          ),
        );
      } else {
        // متن معمولی
        spans.add(
          TextSpan(
            text: '$line\n',
            style: const TextStyle(
              color: Colors.black87,
              fontSize: 15.5,
              fontFamily: 'Vazir',
              height: 1.9,
            ),
          ),
        );
      }
    }

    return TextSpan(children: spans);
  }

  @override
  Widget build(BuildContext context) {
    final filteredGames = _filterGames();

    return Scaffold(
      appBar: AppBar(
        title: const Text(
          'بازی‌های محلی روستای ایراج',
          style: TextStyle(
            fontFamily: 'Vazir',
            fontWeight: FontWeight.bold,
          ),
        ),
        centerTitle: true,
      ),
      body: Column(
        children: [
          // نوار جستجو
          Padding(
            padding: const EdgeInsets.all(12),
            child: TextField(
              onChanged: (value) {
                setState(() {
                  _searchText = value;
                });
              },
              decoration: InputDecoration(
                hintText: 'جستجو در بازی‌ها...',
                hintStyle: const TextStyle(fontFamily: 'Vazir'),
                prefixIcon: const Icon(Icons.search),
                border: OutlineInputBorder(
                  borderRadius: BorderRadius.circular(12),
                ),
                filled: true,
                fillColor: Colors.grey[50],
              ),
            ),
          ),

          // نمایش تعداد نتایج
          if (_searchText.isNotEmpty)
            Padding(
              padding: const EdgeInsets.symmetric(horizontal: 16),
              child: Text(
                '${filteredGames.length} نتیجه برای "$_searchText" یافت شد',
                style: const TextStyle(
                  fontFamily: 'Vazir',
                  color: Colors.grey,
                ),
              ),
            ),

          // لیست بازی‌ها با ExpansionTile
          Expanded(
            child: ListView.builder(
              padding: const EdgeInsets.all(12),
              itemCount: filteredGames.length,
              itemBuilder: (context, index) {
                final game = filteredGames[index];
                final Color headerColor = game['color'] as Color;
                final IconData icon = game['icon'] as IconData;

                // ایجاد رنگ‌های متناوب برای عنوان‌ها
                final bool isEvenIndex = index % 2 == 0;
                final Color titleColor = isEvenIndex
                    ? const Color(0xFF1565C0) // آبی پررنگ‌تر برای آیتم‌های زوج
                    : const Color(0xFF42A5F5); // آبی کم‌رنگ برای آیتم‌های فرد

                return Padding(
                  padding: const EdgeInsets.symmetric(vertical: 6),
                  child: Container(
                    decoration: BoxDecoration(
                      borderRadius: BorderRadius.circular(12),
                      border: Border.all(
                        color: Colors.grey.shade300,
                        width: 1,
                      ),
                      color: Colors.white,
                      boxShadow: [

BoxShadow(
                          color: Colors.grey.withOpacity(0.1),
                          blurRadius: 4,
                          offset: const Offset(0, 2),
                        ),
                      ],
                    ),
                    child: ExpansionTile(
                      key: Key(game['name'] as String),
                      // آیکون بازی در سمت راست
                      trailing: Icon(
                        icon,
                        color: headerColor,
                      ),
                      // فلش در سمت چپ
                      controlAffinity: ListTileControlAffinity.leading,
                      title: Text(
                        game['name'] as String,
                        textAlign: TextAlign.right,
                        style: TextStyle(
                          fontSize: 18,
                          fontWeight: FontWeight.bold,
                          color: titleColor,
                          fontFamily: 'Vazir',
                        ),
                      ),
                      children: [
                        _buildGameContent(game, context),
                      ],
                    ),
                  ),
                );
              },
            ),
          ),
        ],
      ),
    );
  }

  // ویجت برای محتوای داخل ExpansionTile
  Widget _buildGameContent(Map<String, dynamic> game, BuildContext context) {
    return Container(
      padding: const EdgeInsets.all(16),
      decoration: BoxDecoration(
        color: Colors.green.shade50,
        borderRadius: const BorderRadius.only(
          bottomLeft: Radius.circular(12),
          bottomRight: Radius.circular(12),
        ),
      ),
      child: Column(
        crossAxisAlignment: CrossAxisAlignment.start,
        children: [
          // تصویر بازی
          Container(
            height: 180,
            margin: const EdgeInsets.only(bottom: 16),
            alignment: Alignment.center,
            child: _buildGameImage(game),
          ),

          // توضیحات اولیه
          _buildGameSection(
            'توضیحات بازی',
            game['description'] as String,
            Colors.red[700]!,
          ),

          const SizedBox(height: 16),

          // تعداد بازیکنان
          _buildGameSection(
            'تعداد بازیکنان',
            game['players'] as String,
            Colors.red[700]!,
          ),

          const SizedBox(height: 16),

          // لوازم مورد نیاز
          _buildGameSection(
            'لوازم مورد نیاز',
            game['equipment'] as String,
            Colors.red[700]!,
          ),

          const SizedBox(height: 16),

          // جزئیات بازی
          if ((game['details'] as String).isNotEmpty)
            Column(
              children: [
                _buildFormattedGameSection(
                  'جزئیات بازی',
                  game['details'] as String,
                  Colors.red[700]!,
                ),
                const SizedBox(height: 16),
              ],
            ),

          // تاریخچه
          if ((game['history'] as String).isNotEmpty)
            _buildGameSection(
              'تاریخچه',
              game['history'] as String,
              Colors.red[700]!,
            ),
        ],
      ),
    );
  }

  // ویجت برای بخش‌های معمولی بازی
  Widget _buildGameSection(String title, String content, Color titleColor) {
    return Container(
      padding: const EdgeInsets.all(12),
      decoration: BoxDecoration(
        color: Colors.white.withOpacity(0.7),
        borderRadius: BorderRadius.circular(10),
        border: Border.all(color: Colors.grey[300]!, width: 1),
      ),
      child: Column(
        crossAxisAlignment: CrossAxisAlignment.end,
        children: [
          Text(

title,
            textAlign: TextAlign.right,
            style: TextStyle(
              color: titleColor,
              fontSize: 19,
              fontWeight: FontWeight.bold,
              fontFamily: 'Vazir',
            ),
          ),
          const SizedBox(height: 8),
          Text(
            content,
            textAlign: TextAlign.justify,
            style: const TextStyle(
              color: Colors.black87,
              fontSize: 15.5,
              fontFamily: 'Vazir',
              height: 1.9,
            ),
          ),
        ],
      ),
    );
  }

  // ویجت برای بخش‌های با فرمت خاص (جزئیات بازی)
  Widget _buildFormattedGameSection(
      String title, String content, Color titleColor) {
    return Container(
      padding: const EdgeInsets.all(12),
      decoration: BoxDecoration(
        color: Colors.white.withOpacity(0.7),
        borderRadius: BorderRadius.circular(10),
        border: Border.all(color: Colors.grey[300]!, width: 1),
      ),
      child: Column(
        crossAxisAlignment: CrossAxisAlignment.end,
        children: [
          Text(
            title,
            textAlign: TextAlign.right,
            style: TextStyle(
              color: titleColor,
              fontSize: 19,
              fontWeight: FontWeight.bold,
              fontFamily: 'Vazir',
            ),
          ),
          const SizedBox(height: 8),
          Directionality(
            textDirection: TextDirection.rtl,
            child: RichText(
              text: _formatGameText(content),
              textAlign: TextAlign.justify,
            ),
          ),
        ],
      ),
    );
  }

  // ویجت برای نمایش تصویر بازی
  Widget _buildGameImage(Map<String, dynamic> game) {
    final String? imagePath = game['image'] as String?;
    final Color color = game['color'] as Color;
    final IconData icon = game['icon'] as IconData;

    if (imagePath != null && imagePath.isNotEmpty) {
      return ClipRRect(
        borderRadius: BorderRadius.circular(8),
        child: Image.asset(
          imagePath,
          width: double.infinity,
          height: 180,
          fit: BoxFit.cover,
          errorBuilder: (context, error, stackTrace) {
            return Container(
              decoration: BoxDecoration(
                color: color.withOpacity(0.2),
                borderRadius: BorderRadius.circular(8),
              ),
              child: Icon(icon, size: 60, color: color),
            );
          },
        ),
      );
    }

    return Container(
      decoration: BoxDecoration(
        color: color.withOpacity(0.2),
        borderRadius: BorderRadius.circular(8),
      ),
      child: Icon(icon, size: 60, color: color),
    );
  }
}



