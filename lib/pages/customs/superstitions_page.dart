  String normalize(String text) {
    return text
        .replaceAll("ي", "ی")
        .replaceAll("ك", "ک")
        .replaceAll("\u200c", " ")
        .replaceAll(RegExp(r"\s+"), " ")
        .trim()
        .toLowerCase();
  }

  // تابع هایلایت
  Widget highlight(String text, String query) {
    if (query.isEmpty) {
      return Text(
        text,
        textAlign: TextAlign.justify,
        textDirection: TextDirection.rtl,
        style: const TextStyle(
          fontSize: 15,
          height: 1.6,
          fontFamily: "Vazirmatn",
        ),
      );
    }

    final normalizedText = normalize(text);
    final normalizedQuery = normalize(query);

    if (!normalizedText.contains(normalizedQuery)) {
      return Text(
        text,
        textAlign: TextAlign.justify,
        textDirection: TextDirection.rtl,
        style: const TextStyle(
          fontSize: 15,
          height: 1.6,
          fontFamily: "Vazirmatn",
        ),
      );
    }

    final spans = <TextSpan>[];
    int start = 0;
    final textLower = text.toLowerCase();

    while (true) {
      final index = textLower.indexOf(query.toLowerCase(), start);
      if (index < 0) {
        spans.add(TextSpan(text: text.substring(start)));
        break;
      }

      if (index > start) {
        spans.add(TextSpan(text: text.substring(start, index)));
      }

      spans.add(
        TextSpan(
          text: text.substring(index, index + query.length),
          style: const TextStyle(
            backgroundColor: Colors.yellow,
            color: Colors.red,
            fontWeight: FontWeight.bold,
          ),
        ),
      );

      start = index + query.length;
    }

    return RichText(
      textAlign: TextAlign.justify,
      textDirection: TextDirection.rtl,
      text: TextSpan(
        style: const TextStyle(
          fontFamily: "Vazirmatn",
          fontSize: 15,
          color: Colors.black87,
          height: 1.6,
        ),
        children: spans,
      ),
    );
  }

  Widget _buildSectionBox(String title, String content, Color color, String query) {
  // تشخیص درست یا غلط بودن برای نتیجه
  bool isCorrect = content.contains("✅") || content.contains("نتیجه: ✅");
  bool isWrong = content.contains("❌") || content.contains("نتیجه: ❌");
  bool isNeutral = content.contains("⚠️") || content.contains("نتیجه: ⚠️");
  
  Color titleColor = color;
  if (title == "نتیجه") {
    if (isCorrect) titleColor = Colors.green.shade700;
    else if (isWrong) titleColor = Colors.red.shade700;
    else if (isNeutral) titleColor = Colors.orange.shade700;
  }
  
  return Container(
    margin: const EdgeInsets.only(top: 12),
    padding: const EdgeInsets.all(14),
