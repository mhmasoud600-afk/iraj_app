  void _navigateToDetail(Map<String, String> item) {
  // Parse social media from the item
  Map<String, String> socialMedia = {};
  String socialMediaStr = item["social_media"] ?? "";
  if (socialMediaStr.isNotEmpty) {
    socialMediaStr.split(',').forEach((pair) {
      int colonIndex = pair.indexOf(':');
      if (colonIndex != -1) {
        String key = pair.substring(0, colonIndex).trim();
        String value = pair.substring(colonIndex + 1).trim();
        if (key.isNotEmpty && value.isNotEmpty) {
          socialMedia[key] = value;
        }
      }
    });
  }

  Navigator.push(
    context,
    MaterialPageRoute(
      builder: (_) => _CustomJobDetailPage(
        name: item["name"] ?? "",
        desc: item["desc"] ?? "",
        imagePath: item["image"] ?? defaultImage,
        phone: item["phone"] ?? "",
        location: item["location"] ?? "",
        latitude: item["latitude"] ?? "",
        longitude: item["longitude"] ?? "",
        biography: item["biography"] ?? "",
        number: "",
        socialMedia: socialMedia, // ← now passing actual social media
      ),
    ),
  );
}

