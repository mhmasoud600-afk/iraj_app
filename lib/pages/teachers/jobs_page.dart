    }

    return Container(
      margin: const EdgeInsets.symmetric(horizontal: 12, vertical: 8),
      decoration: BoxDecoration(
        color: Colors.pink.shade50,
        borderRadius: BorderRadius.circular(12),
        border: Border.all(
          color: Colors.pink.shade300,
          width: 1.5,
        ),
      ),
      child: Padding(
        padding: const EdgeInsets.all(16),
        child: Column(
          crossAxisAlignment: CrossAxisAlignment.start,
          children: [
            Row(
              children: [
                const Icon(Icons.share, color: Colors.pink, size: 24),
                const SizedBox(width: 8),
                const Text(
                  "شبکه‌های اجتماعی:",
                  style: TextStyle(
                    fontSize: 16,
                    fontWeight: FontWeight.bold,
                    fontFamily: "Vazirmatn",
                    color: Colors.pink,
                  ),
                ),
              ],
            ),
            const SizedBox(height: 12),
            ...widget.socialMedia.entries.map((entry) {
              String title = entry.key;
              String value = entry.value;
              IconData icon;
              Color iconColor;
              if (title.contains("ایتا") || title.contains("Eitaa")) {
                icon = Icons.chat;
                iconColor = Colors.teal;
              } else if (title.contains("اینستاگرام") || title.contains("Instagram")) {
                icon = Icons.camera_alt;
                iconColor = Colors.purple;
              } else if (title.contains("تلگرام") || title.contains("Telegram")) {
                icon = Icons.telegram;
                iconColor = Colors.blue;
              } else if (title.contains("ارسال پیام") || title.contains("پیام")) {
                icon = Icons.message;
                iconColor = Colors.orange;
              } else {
                icon = Icons.link;
                iconColor = Colors.grey;
              }

              return Container(
                margin: const EdgeInsets.only(bottom: 8),
                padding: const EdgeInsets.symmetric(vertical: 6, horizontal: 8),
                decoration: BoxDecoration(
                  color: Colors.white.withOpacity(0.7),
                  borderRadius: BorderRadius.circular(8),
                  border: Border.all(color: Colors.grey.shade200),
                ),
                child: Row(
                  mainAxisAlignment: MainAxisAlignment.spaceBetween,
                  children: [
                    Row(
                      children: [
                        Icon(icon, color: iconColor, size: 22),
                        const SizedBox(width: 8),
                        Text(
                          title,
                          style: const TextStyle(
                            fontWeight: FontWeight.bold,
                            fontFamily: "Vazirmatn",
                            fontSize: 14,
                          ),
                        ),
                      ],
                    ),
                    Expanded(
                      child: GestureDetector(
                        onTap: () => _launchSocialMedia(value),
                        child: Text(
                          value,
                          textDirection: TextDirection.rtl,
                          textAlign: TextAlign.right,
                          style: const TextStyle(
                            color: Colors.blue,
                            decoration: TextDecoration.underline,
                            fontFamily: "Vazirmatn",
                            fontSize: 14,
                          ),
                          maxLines: 1,
                          overflow: TextOverflow.ellipsis,
                        ),
                      ),
                    ),
                    Row(
                      children: [
                        IconButton(
                          icon: const Icon(Icons.open_in_new, size: 18, color: Colors.grey),
                          onPressed: () => _launchSocialMedia(value),
                          tooltip: 'باز کردن',
                          padding: EdgeInsets.zero,
                          constraints: const BoxConstraints(),
                        ),
                        const SizedBox(width: 4),
                        IconButton(
                          icon: const Icon(Icons.copy, size: 18, color: Colors.grey),
