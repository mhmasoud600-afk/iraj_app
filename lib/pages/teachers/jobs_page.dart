  void _openMap(String latitude, String longitude) async {
    final url = 'geo:$latitude,$longitude?q=$latitude,$longitude';
    final Uri launchUri = Uri.parse(url);

    try {
      if (await canLaunchUrl(launchUri)) {
        await launchUrl(launchUri);
      } else {
        final fallbackUrl =
            'https://www.google.com/maps/search/?api=1&query=$latitude,$longitude';
        final Uri fallbackUri = Uri.parse(fallbackUrl);
        if (await canLaunchUrl(fallbackUri)) {
          await launchUrl(fallbackUri);
        } else {
          throw 'Could not open map';
        }
      }
    } catch (e) {
      if (context.mounted) {
        ScaffoldMessenger.of(context).showSnackBar(
          const SnackBar(
            content: Text(
              'خطا در باز کردن نقشه. لطفاً مجدداً تلاش کنید.',
              textAlign: TextAlign.right,
            ),
            backgroundColor: Colors.red,
          ),
        );
      }
    }
  }

  void _launchSocialMedia(String url) async {
    String finalUrl = url.trim();
    if (finalUrl.startsWith('@')) {
      finalUrl = 'https://instagram.com/${finalUrl.substring(1)}';
    } else if (!finalUrl.startsWith('http://') &&
        !finalUrl.startsWith('https://') &&
        !finalUrl.startsWith('tel:') &&
        !finalUrl.startsWith('mailto:')) {
      finalUrl = 'https://$finalUrl';
    }
    final Uri launchUri = Uri.parse(finalUrl);
    try {
      if (await canLaunchUrl(launchUri)) {
        await launchUrl(launchUri);
      } else {
        throw 'Could not launch $finalUrl';
      }
    } catch (e) {
      if (context.mounted) {
        ScaffoldMessenger.of(context).showSnackBar(
          SnackBar(
            content: Text('لینک قابل باز شدن نیست: $url', textAlign: TextAlign.right),
            backgroundColor: Colors.red,
          ),
        );
      }
    }
  }

