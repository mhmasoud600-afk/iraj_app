  void _navigateToDetail(BuildContext context, Map<String, String> item) {
    String imagePath = item["image"] ?? "";
    String finalImagePath = imagePath.isNotEmpty ? imagePath : defaultImage;

    String biography = item["biography"] ?? """
زندگینامه ${item["name"]}:

${item["name"]} از کارمندان متعهد و پرتلاش ایراج هستند که در سازمان مربوطه خدمت می‌کنند.

ایشان با امانتداری، تعهد و تخصص خود، همواره در مسیر خدمت به مردم گام برداشته‌اند و الگویی برای دیگران بوده‌اند.

${item["desc"]}
    """;

    Map<String, dynamic> detailItem = {
      "name": item["name"] ?? "",
      "desc": item["desc"] ?? "",
      "image": finalImagePath,
      "biography": biography,
      "documents": [],
      "number": item["number"] ?? "",
      "pageType": "employee",
      "defaultImage": defaultImage,
    };
    
    Navigator.push(
      context,
      MaterialPageRoute(
        builder: (_) => DetailPage(item: detailItem),
      ),
    );
  }
