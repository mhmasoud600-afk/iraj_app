  Widget _buildSectionHeader(String title, Color color) {
    return Container(
      width: double.infinity,
      margin: const EdgeInsets.all(16),
      padding: const EdgeInsets.all(12),
      decoration: BoxDecoration(
        color: color,
        borderRadius: BorderRadius.circular(12),
        border: Border.all(color: color.withOpacity(0.8), width: 2),
      ),
      child: Text(
        title,
        textDirection: TextDirection.rtl,
        textAlign: TextAlign.center,
        style: const TextStyle(
          fontSize: 22,
          fontWeight: FontWeight.bold,
          color: Colors.blue,
        ),
      ),
    );
  }

  Widget _buildEngineerItem(Map<String, String> item, int index, BuildContext context) {
    Color backgroundColor = index.isEven ? Colors.blue[50]! : Colors.blue[100]!;
    
    // تعیین مسیر تصویر نهایی
    String imagePath = item["image"] ?? "";
    String finalImagePath = imagePath.isNotEmpty ? imagePath : defaultImage;

    return Container(
      margin: const EdgeInsets.symmetric(vertical: 6, horizontal: 8),
      decoration: BoxDecoration(
        color: backgroundColor,
        borderRadius: BorderRadius.circular(12),
        boxShadow: [
          BoxShadow(
            color: Colors.grey.withOpacity(0.2),
            blurRadius: 4,
            offset: const Offset(0, 2),
          ),
        ],
      ),
      child: Material(
        color: Colors.transparent,
        child: InkWell(
          onTap: () => _navigateToDetail(context, item),
          borderRadius: BorderRadius.circular(12),
          child: Padding(
            padding: const EdgeInsets.all(16),
            child: Row(
              children: [
                // تصویر (قابل کلیک)
                GestureDetector(
                  onTap: () => _navigateToDetail(context, item),
                  child: Container(
                    width: 70,
                    height: 70,
                    decoration: BoxDecoration(
                      borderRadius: BorderRadius.circular(10),
                      color: Colors.blue[100],
                      border: Border.all(color: Colors.blue.shade200, width: 1),
                    ),
                    child: ClipRRect(
                      borderRadius: BorderRadius.circular(10),
                      child: Image.asset(
                        finalImagePath,
                        width: 70,
                        height: 70,
                        fit: BoxFit.contain,
                        errorBuilder: (context, error, stackTrace) {
                          // اگر تصویر وجود نداشت، آیکون پیش‌فرض نمایش داده شود
                          return Container(
                            width: 70,
                            height: 70,
                            color: Colors.blue[100],
                            child: const Icon(
                              Icons.engineering,
                              size: 40,
                              color: Colors.blue,
                            ),
                          );
                        },
                      ),
                    ),
                  ),
                ),
                const SizedBox(width: 16),
                // نام و توضیحات (قابل کلیک)
                Expanded(
                  child: GestureDetector(
                    onTap: () => _navigateToDetail(context, item),
                    child: Column(
                      crossAxisAlignment: CrossAxisAlignment.end,
                      children: [
                        Text(
                          item["name"] ?? "",
                          textDirection: TextDirection.rtl,
                          textAlign: TextAlign.right,
                          style: const TextStyle(
                            fontSize: 18,
                            fontWeight: FontWeight.bold,
                            color: Colors.black87,
