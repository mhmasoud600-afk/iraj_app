  void _navigateToDetail(BuildContext context, Map<String, String> item) {
    String imagePath = item["image"] ?? "";
    String finalImagePath = imagePath.isNotEmpty ? imagePath : defaultImage;

    String biography = item["biography"] ?? """
زندگینامه ${item["name"]}:

${item["name"]} از فرزندان برومند روستای ایراج هستند که در رشته مهندسی تحصیل کرده‌اند.

ایشان پس از گذراندن دوران تحصیل خود در دانشگاه‌های معتبر کشور، در زمینه تخصصی خود مشغول به فعالیت شده‌اند و همواره به عنوان یک الگوی موفق برای جوانان روستا شناخته می‌شوند.

${item["desc"]}
    """;

    Map<String, dynamic> detailItem = {
      "name": item["name"] ?? "",
      "desc": item["desc"] ?? "",
      "image": finalImagePath,
      "biography": biography,
      "documents": [],
      "number": item["number"] ?? "",
      "pageType": "engineer",
      "defaultImage": defaultImage,
    };
    
    Navigator.push(
      context,
      MaterialPageRoute(
        builder: (_) => DetailPage(item: detailItem),
      ),
    );
  }
